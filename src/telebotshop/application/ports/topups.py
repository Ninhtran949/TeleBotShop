from collections.abc import Sequence
from datetime import datetime
from typing import Protocol
from uuid import UUID

from telebotshop.domain.models.topups import Settlement, SettlementResult, TopUpIntent


class TopUpRepository(Protocol):
    async def by_action(self, buyer_id: UUID, action_id: UUID) -> TopUpIntent | None: ...
    async def save(self, intent: TopUpIntent) -> None: ...
    async def get(self, intent_id: UUID) -> TopUpIntent | None: ...
    async def own(self, buyer_id: UUID, offset: int) -> tuple[TopUpIntent, ...]: ...
    async def route(self, buyer_id: UUID): ...
    async def active_route_intent(self, route_id: UUID) -> TopUpIntent | None: ...
    async def has_settlement(self, intent_id: UUID) -> bool: ...
    async def reject_unused_quote(self, intent_id: UUID) -> None: ...
    async def set_route(self, buyer_id: UUID, network: str, token: str, recipient: str) -> None: ...
    async def observe(self, event: Settlement) -> tuple[UUID, bool, Settlement]: ...
    async def evidence(self, event_id: UUID) -> Settlement | None: ...
    async def match(self, event: Settlement) -> TopUpIntent | None: ...
    async def event_result(self, event_id: UUID) -> SettlementResult: ...
    async def finish(
        self,
        event_id: UUID,
        intent: TopUpIntent | None,
        state: str,
        reason: str | None,
        journal_id: UUID | None = None,
    ) -> None: ...
    async def queue(self, offset: int) -> tuple[SettlementResult, ...]: ...
    async def save_review(
        self,
        action_id: UUID,
        actor_id: UUID,
        event_id: UUID,
        intent_id: UUID | None,
        reason: str,
        source: bytes,
        expires_at: datetime,
        decision: str = "APPROVE",
    ) -> None: ...
    async def review(self, action_id: UUID): ...
    async def apply_review(self, action_id: UUID) -> None: ...
    async def checkpoint(self, provider: str) -> datetime | None: ...
    async def advance(self, provider: str, before: datetime) -> None: ...


class SettlementReader(Protocol):
    provider: str

    async def read(self, after: datetime, before: datetime, page: int) -> Sequence[Settlement]: ...
