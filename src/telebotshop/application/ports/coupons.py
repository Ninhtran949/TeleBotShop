from typing import Protocol
from uuid import UUID

from telebotshop.domain.models.coupons import Coupon, CouponQuote
from telebotshop.domain.models.orders import Order


class CouponRepository(Protocol):
    async def get(self, coupon_id: UUID, *, for_update: bool = False) -> Coupon | None: ...
    async def by_code(self, code: str, *, for_update: bool = False) -> Coupon | None: ...
    async def list(self, offset: int) -> tuple[Coupon, ...]: ...
    async def save(self, coupon: Coupon) -> bool: ...
    async def change(self, action_id: UUID) -> tuple[UUID, UUID, bool] | None: ...
    async def set_active(
        self, coupon: Coupon, active: bool, actor_id: UUID, action_id: UUID
    ) -> None: ...
    async def uses(self, coupon_id: UUID, buyer_id: UUID) -> tuple[int, int]: ...
    async def redemption(self, order_id: UUID) -> CouponQuote | None: ...
    async def redeem(self, order: Order, quote: CouponQuote) -> None: ...
