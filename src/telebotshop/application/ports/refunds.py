from collections.abc import Awaitable, Callable
from datetime import datetime
from typing import Protocol
from uuid import UUID

from telebotshop.domain.models.catalog import Page
from telebotshop.domain.models.inventory import SealedPayload
from telebotshop.domain.models.payments import StoredPayment
from telebotshop.domain.models.refunds import (
    RefundIntent,
    RefundReceipt,
    RefundRequest,
    RefundResult,
    RefundSnapshot,
    RefundState,
    RefundView,
    StarEvidence,
)


class RefundGateway(Protocol):
    async def refund(self, request: RefundRequest) -> RefundResult: ...
    async def transactions(self, offset: int) -> tuple[StarEvidence, ...]: ...


class RefundRepository(Protocol):
    async def payment(self, payment_id: UUID) -> StoredPayment | None: ...
    async def view(self, payment_id: UUID) -> RefundView | None: ...
    async def queue(self, page: int) -> Page[RefundView]: ...
    async def snapshot(self, payment_id: UUID) -> RefundSnapshot: ...
    async def payer(self, payment_id: UUID) -> int | None: ...
    async def verify(self, payment_id: UUID, actor_id: UUID, evidence: StarEvidence) -> None: ...
    async def active(self, payment_id: UUID) -> RefundIntent | None: ...
    async def intent(self, intent_id: UUID, *, for_update: bool = False) -> RefundIntent | None: ...
    async def save(self, intent: RefundIntent, evidence: SealedPayload | None) -> None: ...
    async def evidence(self, intent_id: UUID) -> SealedPayload: ...
    async def start(self, intent: RefundIntent, now: datetime, deadline: datetime) -> None: ...
    async def finish(
        self,
        intent: RefundIntent,
        state: RefundState,
        now: datetime,
        confirmed_by: str | None = None,
    ) -> None: ...
    async def observe(self, intent: RefundIntent, result: RefundResult) -> None: ...
    async def hold(self, intent: RefundIntent, *, release: bool = False) -> None: ...
    async def mark_refunded(self, payment: StoredPayment) -> None: ...
    async def receipt(self, receipt: RefundReceipt) -> None: ...
    async def matching_receipt(self, payment: StoredPayment) -> str | None: ...
    async def audit(self, intent: RefundIntent, event: str) -> None: ...
    async def audit_operation(
        self,
        actor_id: UUID,
        payment_id: UUID,
        event: str,
        correlation_id: UUID,
        refund_id: UUID | None = None,
    ) -> None: ...


type RefundReceiver = Callable[[RefundReceipt], Awaitable[RefundIntent | None]]
